"""Model functions importable from their package (`from financetoolkit.models import ...`).

Each package's `__init__.py` is generated from its *_model.py modules. After adding, renaming or
removing a model function, rewrite them with:

    python tests/test_model_imports.py
"""

import ast
import importlib
import pathlib
import subprocess
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]

# The calculation packages; economics and discovery hold data retrieval, and the `sources`
# folders of the other packages too, so those are left out.
PACKAGES = {
    "econometrics": "Econometrics",
    "etf": "ETF",
    "fixedincome": "Fixed Income",
    "models": "Models",
    "options": "Options",
    "performance": "Performance",
    "portfolio": "Portfolio",
    "ratios": "Ratios",
    "risk": "Risk",
    "technicals": "Technicals",
}

TEMPLATE = '''"""
The model functions of the {title} module, importable from the package itself, e.g.
`from financetoolkit.{package} import {example}`. A model module is imported when one of its
functions is first used.
"""

# Generated by tests/test_model_imports.py: run `python tests/test_model_imports.py` after adding,
# renaming or removing a function in one of the package's *_model.py modules.

from typing import TYPE_CHECKING

from financetoolkit.helpers import import_functions_when_used

_MODULES = {{
{modules}
}}

__all__ = [
{names}
]

if TYPE_CHECKING:
{imports}

__getattr__, __dir__ = import_functions_when_used(__name__, _MODULES)
'''


def collect_functions(package: str) -> dict[str, list[str]]:
    """The public functions of each model module of a package, keyed by module name."""
    modules = {}
    for path in sorted((ROOT / "financetoolkit" / package).rglob("*_model.py")):
        if "sources" in path.relative_to(ROOT).parts:
            continue
        names = sorted(
            node.name
            for node in ast.parse(path.read_text()).body
            if isinstance(node, ast.FunctionDef) and not node.name.startswith("_")
        )
        if names:
            module = ".".join(path.relative_to(ROOT).with_suffix("").parts)
            modules[module] = names
    return modules


def find_duplicates(modules: dict[str, list[str]]) -> dict[str, list[str]]:
    """Function names that more than one model module of the package defines."""
    found: dict[str, list[str]] = {}
    for module, names in modules.items():
        for name in names:
            found.setdefault(name, []).append(module)
    return {name: where for name, where in found.items() if len(where) > 1}


def render(package: str) -> str:
    """The `__init__.py` of a package."""
    modules = collect_functions(package)
    duplicates = find_duplicates(modules)
    if duplicates:
        raise ValueError(
            f"{package} defines these functions more than once: {duplicates}"
        )
    names = sorted(name for functions in modules.values() for name in functions)
    return TEMPLATE.format(
        title=PACKAGES[package],
        package=package,
        example=names[0],
        modules="\n".join(
            f'    "{module}": [\n'
            + "".join(f'        "{name}",\n' for name in functions)
            + "    ],"
            for module, functions in modules.items()
        ),
        names="\n".join(f'    "{name}",' for name in names),
        imports="\n".join(
            f"    from {module} import (\n"
            + "".join(f"        {name},\n" for name in functions)
            + "    )"
            for module, functions in modules.items()
        ),
    )


def read_init(package: str) -> tuple[dict, list, dict]:
    """The `_MODULES`, `__all__` and type-checking imports of a package's `__init__.py`."""
    tree = ast.parse((ROOT / "financetoolkit" / package / "__init__.py").read_text())
    values, imports = {}, {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            values[node.targets[0].id] = ast.literal_eval(node.value)
        elif isinstance(node, ast.If):
            for statement in node.body:
                if isinstance(statement, ast.ImportFrom):
                    imports[statement.module] = sorted(
                        alias.name for alias in statement.names
                    )
    return values.get("_MODULES", {}), values.get("__all__", []), imports


@pytest.mark.parametrize("package", PACKAGES)
def test_package_imports_every_model_function(package):
    modules = collect_functions(package)
    assert not find_duplicates(
        modules
    ), "A function name must mean one thing within a package"

    stated_modules, stated_all, stated_imports = read_init(package)
    message = "Out of date: run `python tests/test_model_imports.py`"
    assert {
        module: sorted(names) for module, names in stated_modules.items()
    } == modules, message
    assert sorted(stated_all) == sorted(
        name for names in modules.values() for name in names
    ), message
    assert stated_imports == modules, message


@pytest.mark.parametrize("package", PACKAGES)
def test_package_functions_are_the_model_functions(package):
    imported = importlib.import_module(f"financetoolkit.{package}")
    for module, names in collect_functions(package).items():
        model = importlib.import_module(module)
        for name in names:
            assert getattr(imported, name) is getattr(model, name)
    assert set(imported.__all__) <= set(dir(imported))
    with pytest.raises(AttributeError):
        imported.get_this_does_not_exist  # noqa: B018


def test_import_from_the_package():
    from financetoolkit.models import get_days_sales_in_receivables_index
    from financetoolkit.models.quality.beneish_model import (
        get_days_sales_in_receivables_index as defined,
    )

    assert get_days_sales_in_receivables_index is defined


def test_packages_import_their_models_when_used():
    # In a fresh interpreter: importing the package loads no model module until a function is used.
    code = (
        "import sys, financetoolkit.risk as risk\n"
        "before = 'financetoolkit.risk.value_at_risk.var_model' in sys.modules\n"
        "risk.get_var_historic\n"
        "print(before, 'financetoolkit.risk.value_at_risk.var_model' in sys.modules)"
    )
    result = subprocess.run(  # noqa: S603
        [sys.executable, "-c", code],
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    assert result.stdout.split() == ["False", "True"]


if __name__ == "__main__":
    written = []
    for package in PACKAGES:
        path = ROOT / "financetoolkit" / package / "__init__.py"
        path.write_text(render(package))
        written.append(str(path))
    subprocess.run(  # noqa: S603
        [sys.executable, "-m", "ruff", "check", "--fix", "--quiet", *written],
        check=False,
    )
    subprocess.run(  # noqa: S603
        [sys.executable, "-m", "black", "--quiet", *written], check=False
    )
    print(f"Wrote {len(written)} files.")
